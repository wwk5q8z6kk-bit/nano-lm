"""Aggregate LAB-ARCH-02 results into a table with seed means, spreads and prereg decisions.

usage: python -m lab.arch.analyze [/Volumes/Express1M2/nanolm-lab/runs] > lab/reports/LAB-ARCH-02_results.md
"""

from __future__ import annotations

import json
import statistics as st
import sys
from collections import defaultdict
from pathlib import Path

DOMS = ["web", "textbook", "math", "code"]


def load(root: Path):
    rows = []
    for f in sorted(root.glob("*/result.json")):
        r = json.loads(f.read_text())
        if r.get("final") is None or "smoke" in r["run"]:
            continue
        rows.append(r)
    return rows


def main():
    root = Path(sys.argv[1] if len(sys.argv) > 1 else "/Volumes/Express1M2/nanolm-lab/runs")
    rows = load(root)
    groups = defaultdict(list)
    for r in rows:
        groups[(r["arm"], r["optim"], r.get("match", "tokens"))].append(r)

    def m(vals):
        return (st.mean(vals), (max(vals) - min(vals)) / 2 if len(vals) > 1 else float("nan"))

    ref = groups.get(("T0_dense", "adamw", "tokens"))
    ref_c = st.mean(r["final"]["bpb_composite"] for r in ref) if ref else None
    ref_d = {d: st.mean(r["final"]["bpb"][d] for r in ref) for d in DOMS} if ref else None
    ref_spread = m([r["final"]["bpb_composite"] for r in ref])[1] if ref and len(ref) > 1 else None

    print("# LAB-ARCH-02 results (auto-generated by lab/arch/analyze.py)\n")
    print(f"Runs: {len(rows)}. Values = mean over seeds; ± = half-range across seeds. "
          "Δ% is relative to T0_dense/adamw/tokens (negative = better).\n")
    print("| Arm | Optim | Match | n | Tokens | Train TFLOP·s | Composite BPB | Δ% vs T0 | web | textbook | math | code "
          "| copy loss | ctx gain (nats) | tok/s (4090) | Decision |")
    print("|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|")
    order = sorted(groups, key=lambda k: st.mean(r["final"]["bpb_composite"] for r in groups[k]))
    for k in order:
        g = groups[k]
        c, cs = m([r["final"]["bpb_composite"] for r in g])
        doms = {d: st.mean(r["final"]["bpb"][d] for r in g) for d in DOMS}
        copy = st.mean(r["final"]["copy_loss_second_half"] for r in g)
        ctx = st.mean(r["final"]["web_loss_pos_0_64"] - r["final"]["web_loss_pos_last_256"] for r in g)
        tps = st.mean(r["train_tok_s"] for r in g)
        flops = st.mean(r.get("train_flops_total", 0) for r in g) / 1e12
        toks = st.mean(r["tokens"] for r in g) / 1e6
        delta = 100 * (c / ref_c - 1) if ref_c else float("nan")
        dec = ""
        if ref_c and k != ("T0_dense", "adamw", "tokens"):
            worst = max(100 * (doms[d] / ref_d[d] - 1) for d in DOMS)
            consistent = all(r["final"]["bpb_composite"] < ref_c for r in g) if delta < 0 else \
                all(r["final"]["bpb_composite"] > ref_c for r in g)
            if len(g) < 2:
                dec = "pending 2nd seed"
            elif abs(delta) < 1.0:
                dec = "no detectable difference (<1%)"
            elif delta <= -1.0 and consistent and worst <= 1.0:
                dec = "**WIN** (prereg rule met)"
            elif delta <= -1.0:
                dec = "better on mean; rule not met" + ("" if consistent else " (seed-inconsistent)") + \
                      ("" if worst <= 1.0 else f" (a domain regresses {worst:+.1f}%)")
            else:
                dec = "worse"
        print(f"| {k[0]} | {k[1]} | {k[2]} | {len(g)} | {toks:.0f}M | {flops:.3g} | {c:.4f} ± {cs:.4f} | {delta:+.2f} | "
              + " | ".join(f"{doms[d]:.4f}" for d in DOMS)
              + f" | {copy:.3f} | {ctx:+.3f} | {tps:,.0f} | {dec} |")
    if ref_spread is not None:
        print(f"\nT0 seed half-range on composite BPB: {ref_spread:.4f} ({100*ref_spread/ref_c:.2f}%).")
    print("\nctx gain = loss(positions 0–64) − loss(last 256 positions) on web val: larger = better use of long context.")


if __name__ == "__main__":
    main()
